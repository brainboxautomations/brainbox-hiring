-- Grant the API roles explicitly instead of inheriting them from project defaults.
--
-- Every migration before this one assumed Supabase's legacy default privileges:
-- a table, sequence or function created by `postgres` in `public` was granted to
-- anon, authenticated and service_role automatically, and later migrations only
-- REVOKE where exposure is unwanted. Projects created after Supabase changed that
-- default (production, 2026-09) get no DML on new tables for those roles, no
-- sequence access, and no EXECUTE for service_role on functions whose PUBLIC
-- grant was revoked. The first symptom was /careers answering 500 with
-- "permission denied for table positions".
--
-- The statements below are exactly the privileges the development project holds
-- and production lacked, generated by diffing both catalogs after 0001–0046.
-- Development already holds every one of them, so this migration is a no-op
-- there. Nothing is granted that development does not already grant; RLS still
-- governs every row.
--
-- The default-privilege block restores the legacy behaviour for objects created
-- by later migrations, so both projects keep behaving identically and a future
-- migration's REVOKEs mean the same thing in each.

alter default privileges for role postgres in schema public
  grant select, insert, update, delete on tables to anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  grant usage, select, update on sequences to anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  grant execute on functions to anon, authenticated, service_role;

